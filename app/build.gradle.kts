        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
        // Robolectric precisa dos recursos (fontes Inter e Material Symbols) para as capturas de tela.
