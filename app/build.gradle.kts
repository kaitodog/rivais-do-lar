fun loadProps(name: String): Properties = Properties().apply {
    val f = rootProject.file(name)
    if (f.exists()) f.inputStream().use { load(it) }
}

val localProps = loadProps("local.properties")
val keystoreProps = loadProps("keystore.properties")

// Credenciais nunca ficam no git: vêm de local.properties (dev) ou de variáveis de ambiente (CI).
fun secret(key: String): String =
    localProps.getProperty(key) ?: System.getenv(key) ?: ""

// keystore.properties (local) ou variáveis de ambiente (GitHub Actions).
fun signing(key: String, env: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(env)

val releaseStoreFile = signing("storeFile", "KEYSTORE_PATH")

android {
    namespace = "com.rivaisdolar.app"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.rivaisdolar.app"
